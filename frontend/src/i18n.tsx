export type TKey = keyof Dict
export type T = (key: TKey, vars?: Record<string, string | number>) => string

const dicts: Record<Lang, Dict> = { en, zh }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export const browserLang = (): Lang => (navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en')

const I18nContext = createContext<{ lang: Lang; t: T }>({ lang: 'en', t: (k, v) => translate('en', k, v) })

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const value = useMemo(() => ({ lang, t: ((k, v) => translate(lang, k, v)) as T }), [lang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)

export const groupLabel = (t: T, g: MuscleGroup) => t(`g.${g}` as TKey)
